// Invoked by check-highlights.py --ui against its isolated worker and library.
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { chromium } = require('playwright')

async function main() {
  const mid = process.argv[2]
  const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+a7x8AAAAASUVORK5CYII=', 'base64')
  const browser = await chromium.launch({ headless: true, channel: 'msedge' })
  try {
    const context = await browser.newContext({ viewport: { width: 1200, height: 900 }, permissions: ['clipboard-read', 'clipboard-write'] })
    const page = await context.newPage()
    const errors = []
    page.on('pageerror', e => errors.push(e.message))
    // Give Vite a short startup window without visiting an unrelated server.
    for (let attempt = 0; ; attempt++) {
      try { await page.goto(`http://127.0.0.1:1420/#/library/all?movie=${mid}`); break }
      catch (e) { if (attempt === 30) throw e; await new Promise(resolve => setTimeout(resolve, 100)) }
    }
    const section = page.locator('.movie-highlights')
    await section.getByRole('button', { name: '添加记录', exact: true }).waitFor()
    await section.locator('.highlight-card').first().waitFor()
    const originalCount = await section.locator('.highlight-card').count()
    await section.getByRole('button', { name: '添加记录', exact: true }).click()
    const form = section.locator('form')
    assert.equal(await form.locator('input[required]').count(), 0)
    await form.getByRole('button', { name: '保存', exact: true }).click()
    await form.getByRole('alert').waitFor()
    await form.getByLabel('开始时间（可选）', { exact: true }).fill('00:10:00')
    await form.getByLabel('结束时间（可选）', { exact: true }).fill('00:09:00')
    await form.getByRole('button', { name: '保存', exact: true }).click()
    assert.match(await form.getByRole('alert').textContent(), /开始时间/)
    await form.getByLabel('开始时间（可选）', { exact: true }).fill('')
    await form.getByLabel('结束时间（可选）', { exact: true }).fill('')
    await form.locator('input[type=file]').setInputFiles({ name: 'ui.png', mimeType: 'image/png', buffer: png })
    const saveResponse = page.waitForResponse(r => r.url().endsWith(`/movies/${mid}/highlights`) && r.request().method() === 'POST')
    await form.getByRole('button', { name: '保存', exact: true }).click()
    assert.equal((await saveResponse).status(), 200)
    await form.waitFor({ state: 'hidden' })
    assert.equal(await section.locator('.highlight-card').count(), originalCount + 1)
    const newCard = section.locator('.highlight-card').last()
    assert.equal(await newCard.locator('h3').textContent(), '精彩记录')
    await newCard.getByRole('button', { name: '查看图片 ui.png' }).click()
    const preview = page.getByRole('dialog', { name: '精彩记录', exact: true })
    await preview.waitFor()
    assert(await preview.locator('img').evaluate(img => img.complete && img.naturalWidth > 0))
    await page.keyboard.press('Escape')
    await preview.waitFor({ state: 'hidden' })
    assert(await section.isVisible())
    await newCard.getByRole('button', { name: '编辑', exact: true }).click()
    await form.getByLabel('备注（可选）', { exact: true }).fill('浏览器编辑验证')
    const updateResponse = page.waitForResponse(r => r.url().includes(`/movies/${mid}/highlights/`) && r.request().method() === 'PUT')
    await form.getByRole('button', { name: '保存', exact: true }).click()
    assert.equal((await updateResponse).status(), 200)
    await form.waitFor({ state: 'hidden' })
    assert.equal(await section.getByText('浏览器编辑验证', { exact: true }).count(), 1)
    await newCard.getByRole('button', { name: '编辑', exact: true }).click()
    await form.getByLabel('标题（可选）', { exact: true }).fill('未保存修改')
    page.once('dialog', dialog => dialog.dismiss())
    await page.getByRole('button', { name: '返回影片列表', exact: true }).first().click()
    assert(await form.isVisible())
    assert.equal(await form.getByLabel('标题（可选）', { exact: true }).inputValue(), '未保存修改')
    page.once('dialog', dialog => dialog.dismiss())
    await page.getByRole('link', { name: '搜索', exact: true }).click()
    assert(page.url().includes(`/library/all?movie=${mid}`))
    assert(await form.isVisible())
    page.once('dialog', dialog => dialog.accept())
    await form.getByRole('button', { name: '取消', exact: true }).click()
    await form.waitFor({ state: 'hidden' })
    await section.getByRole('button', { name: /^复制时间:/ }).first().click()
    assert((await page.evaluate(() => navigator.clipboard.readText())).startsWith('00:00:00'))

    // Generate a real, silent WebM with native browser APIs to check clip playback.
    const clipBase64 = await page.evaluate(() => new Promise(resolve => {
      const canvas = document.createElement('canvas'); canvas.width = 160; canvas.height = 90
      const ctx = canvas.getContext('2d'); ctx.fillStyle = '#263d53'; ctx.fillRect(0, 0, 160, 90)
      const stream = canvas.captureStream(10)
      const recorder = new MediaRecorder(stream, { mimeType: 'video/webm;codecs=vp8' })
      const chunks = []; recorder.ondataavailable = event => chunks.push(event.data)
      recorder.onstop = () => {
        stream.getTracks().forEach(track => track.stop())
        const reader = new FileReader(); reader.onload = () => resolve(reader.result.split(',')[1])
        reader.readAsDataURL(new Blob(chunks, { type: 'video/webm' }))
      }
      recorder.start(); setTimeout(() => recorder.stop(), 700)
    }))
    await section.getByRole('button', { name: '添加记录', exact: true }).click()
    await form.locator('input[type=file]').setInputFiles({ name: 'clip.webm', mimeType: 'video/webm', buffer: Buffer.from(clipBase64, 'base64') })
    const clipResponse = page.waitForResponse(r => r.url().endsWith(`/movies/${mid}/highlights`) && r.request().method() === 'POST')
    await form.getByRole('button', { name: '保存', exact: true }).click()
    assert.equal((await clipResponse).status(), 200)
    await form.waitFor({ state: 'hidden' })
    const clipCard = section.locator('.highlight-card').filter({ has: page.getByRole('button', { name: '播放片段 clip.webm' }) })
    await clipCard.getByRole('button', { name: '播放片段 clip.webm' }).click()
    await page.waitForFunction(() => { const video = document.querySelector('video[aria-label="clip.webm"]'); return video && video.readyState >= 2 && video.videoWidth === 160 })
    await page.keyboard.press('Escape')
    page.once('dialog', dialog => dialog.accept())
    const removeClip = page.waitForResponse(r => r.url().includes(`/movies/${mid}/highlights/`) && r.request().method() === 'DELETE')
    await clipCard.getByRole('button', { name: '删除', exact: true }).click()
    assert.equal((await removeClip).status(), 204)
    await clipCard.waitFor({ state: 'hidden' })

    const output = path.join(process.cwd(), '.tmp', 'highlight-checks')
    fs.mkdirSync(output, { recursive: true })
    await section.locator('h2').scrollIntoViewIfNeeded()
    await page.screenshot({ path: path.join(output, 'highlights-dark.png'), fullPage: true })
    await page.evaluate(() => document.documentElement.setAttribute('data-theme', 'light'))
    const titleColor = await section.locator('h3').first().evaluate(el => getComputedStyle(el).color)
    assert.equal(titleColor, 'rgb(26, 29, 36)')
    await page.screenshot({ path: path.join(output, 'highlights-light.png'), fullPage: true })
    await page.setViewportSize({ width: 900, height: 700 })
    assert(await section.evaluate(el => el.scrollWidth <= el.clientWidth + 2))
    await page.reload()
    await section.getByText('浏览器编辑验证', { exact: true }).waitFor()
    assert.equal(await section.locator('.highlight-card').count(), originalCount + 1)
    page.once('dialog', dialog => dialog.accept())
    const deleteResponse = page.waitForResponse(r => r.url().includes(`/movies/${mid}/highlights/`) && r.request().method() === 'DELETE')
    await section.locator('.highlight-card').last().getByRole('button', { name: '删除', exact: true }).click()
    assert.equal((await deleteResponse).status(), 204)
    await page.waitForFunction(count => document.querySelectorAll('.highlight-card').length === count, originalCount)
    assert.deepEqual(errors, [])
    console.log('PASS browser: optional-title image/clip saves, empty/time validation, image and real-video previews, edit, dirty close/navigation guards, clipboard, reload, delete, dark/light contrast, 900px layout.')
  } finally { await browser.close() }
}
main().catch(e => { console.error(e); process.exit(1) })
